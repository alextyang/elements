import { writeFile } from "node:fs/promises";

const endpoint = new URL("https://vizier.cds.unistra.fr/viz-bin/asu-tsv");
endpoint.searchParams.set("-source", "I/239/hip_main");
endpoint.searchParams.set("-out", "HIP,RAICRS,DEICRS,Vmag,B-V");
endpoint.searchParams.set("Vmag", "<6.51");
endpoint.searchParams.set("-out.max", "12000");

const response = await fetch(endpoint);
if (!response.ok) {
    throw new Error(`VizieR returned ${response.status}`);
}

const rows = (await response.text())
    .split("\n")
    .filter((line) => line && !line.startsWith("#"))
    .slice(3)
    .map((line) => line.split("\t").map((value) => value.trim()))
    .map(([id, ra, dec, magnitude, bv]) => ({
        id: Number(id),
        ra: Number(ra),
        dec: Number(dec),
        magnitude: Number(magnitude),
        bv: Number(bv),
    }))
    .filter(
        (star) =>
            Number.isFinite(star.id) &&
            Number.isFinite(star.ra) &&
            Number.isFinite(star.dec) &&
            Number.isFinite(star.magnitude),
    )
    .sort((left, right) => left.magnitude - right.magnitude || left.id - right.id);

const data = rows
    .map(
        (star) =>
            `${star.id},${star.ra.toFixed(6)},${star.dec.toFixed(6)},${star.magnitude.toFixed(2)},${Number.isFinite(star.bv) ? star.bv.toFixed(3) : "0.650"}`,
    )
    .join(";\n");

const source = `export interface CatalogStar {
    id: number;
    /** ICRS right ascension in degrees. */
    ra: number;
    /** ICRS declination in degrees. */
    dec: number;
    /** Johnson V apparent magnitude. */
    mag: number;
    /** Johnson B-V color index. */
    bv: number;
}

/**
 * Hipparcos entries through V=6.5 from the ESA Hipparcos Main Catalogue.
 * Coordinates, V magnitudes, and B-V indices are sourced from CDS VizieR
 * catalogue I/239/hip_main (ESA 1997). Generated by update-star-catalog.mjs.
 */
const HIPPARCOS_DATA = \`${data}\`;

export const HIPPARCOS_STARS: CatalogStar[] = HIPPARCOS_DATA
    .split(";\\n")
    .map((entry) => {
        const [id, ra, dec, mag, bv] = entry.split(",").map(Number);
        return { id, ra, dec, mag, bv };
    });
`;

await writeFile(
    new URL("../components/backgrounds/sky/star-catalog.ts", import.meta.url),
    source,
);

console.log(`Wrote ${rows.length} Hipparcos stars through V=6.5`);
